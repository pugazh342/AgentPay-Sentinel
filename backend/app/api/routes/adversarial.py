"""Adversarial security report endpoints.

Note: This module uses lazy imports to avoid circular dependencies with the test
module. The adversarial runner is imported at function call time, not module load
time. Execution is mock/stub-only and writes reports to the fixed reports path.
"""

from __future__ import annotations

import json
import logging
import os
import threading
from concurrent.futures import ThreadPoolExecutor, TimeoutError as FuturesTimeoutError
from pathlib import Path

from fastapi import APIRouter, Request

from app.domain.errors import AppError

logger = logging.getLogger("agentpay")

router = APIRouter(
    prefix="/api/adversarial",
    tags=["Adversarial"],
    dependencies=[],
)

_REPORTS_DIR = Path(__file__).resolve().parents[3] / "reports"
_RUN_LOCK = threading.Lock()


class AdversarialRunnerDisabledError(AppError):
    status_code = 403
    code = "ADVERSARIAL_RUNNER_DISABLED"

    def __init__(self, message: str = "Adversarial runner is disabled.") -> None:
        super().__init__(message, code=self.code)


class AdversarialRunnerBusyError(AppError):
    status_code = 409
    code = "ADVERSARIAL_RUNNER_BUSY"

    def __init__(self, message: str = "An adversarial run is already in progress.") -> None:
        super().__init__(message, code=self.code)


class AdversarialRunnerTimeoutError(AppError):
    status_code = 504
    code = "ADVERSARIAL_RUNNER_TIMEOUT"

    def __init__(self, message: str = "Adversarial runner exceeded the allowed execution time.") -> None:
        super().__init__(message, code=self.code)


class AdversarialRunnerFailedError(AppError):
    status_code = 500
    code = "ADVERSARIAL_RUNNER_FAILED"

    def __init__(self, message: str = "Adversarial runner execution failed.") -> None:
        super().__init__(message, code=self.code)


def _get_report_paths():
    """Get JSON and Markdown report paths."""
    return _REPORTS_DIR / "adversarial_report.json", _REPORTS_DIR / "adversarial_report.md"


def _verify_no_secrets_in_report(report_text: str) -> None:
    """Verify no configured secrets appear in the rendered report."""
    # Lazy import to avoid circular dependency
    from app.security_testing.reporting import assert_secret_free

    secret_values = []

    # Add test HMAC secret
    try:
        from tests.conftest import TEST_HMAC_SECRET

        secret_values.append(TEST_HMAC_SECRET)
    except Exception:
        pass

    # Collect secret values from environment
    for key in (
        "AGENTPAY_HMAC_SECRET",
        "HMAC_SECRET",
        "PAYPAL_CLIENT_ID",
        "PAYPAL_CLIENT_SECRET",
        "PAYPAL_WEBHOOK_ID",
        "AGENTPAY_PAYPAL_CLIENT_ID",
        "AGENTPAY_PAYPAL_CLIENT_SECRET",
        "AGENTPAY_PAYPAL_WEBHOOK_ID",
        "GEMINI_API_KEY",
        "AGENTPAY_GEMINI_API_KEY",
        "AGENTPAY_GROQ_API_KEY",
        "GROQ_API_KEY",
    ):
        val = os.environ.get(key)
        if val:
            secret_values.append(val)

    # Filter empty and deduplicate by length (longest first)
    secret_values = tuple(
        sorted({v for v in secret_values if v}, key=len, reverse=True)
    )

    assert_secret_free(report_text, secret_values)


@router.get(
    "/report",
    summary="Get the latest adversarial security report",
    description=(
        "Returns the deterministic adversarial security report as JSON. "
        "The report is generated by executing all scenarios against the real application. "
        "If no report exists, returns 404 with a clear error message."
    ),
    responses={
        404: {"description": "Report not found. Run POST /api/adversarial/run first."},
    },
)
def get_adversarial_report() -> dict:
    """Return the persisted adversarial report as JSON."""
    json_path, _ = _get_report_paths()

    if not json_path.exists():
        from fastapi import HTTPException

        raise HTTPException(
            status_code=404,
            detail={
                "error": {
                    "code": "REPORT_NOT_FOUND",
                    "message": "Adversarial report not found. Execute POST /api/adversarial/run to generate it.",
                }
            },
        )

    with open(json_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    # Verify no secrets leaked into the report
    text = json_path.read_text(encoding="utf-8")
    _verify_no_secrets_in_report(text)

    return data


def _runner_explicitly_enabled(request: Request) -> bool:
    settings = getattr(request.app.state, "settings", None)
    if settings is not None and bool(getattr(settings, "adversarial_runner_enabled", False)):
        return True
    return os.environ.get("AGENTPAY_ADVERSARIAL_RUNNER_ENABLED", "").strip().lower() in {
        "1",
        "true",
        "yes",
        "on",
    }


def _is_local_demo_context(request: Request) -> bool:
    settings = getattr(request.app.state, "settings", None)
    env_setting = (getattr(settings, "environment", "local") or "local").strip().lower()
    env_var = (os.environ.get("AGENTPAY_ENVIRONMENT", "local") or "local").strip().lower()
    # Disabled by default outside authorized local execution. Allow explicit local/test
    # demo contexts only; never allow production contexts.
    allowed = {"local", "test", "dev", "development"}
    return env_setting in allowed and env_var not in {"production", "prod", "staging"}


@router.post(
    "/run",
    summary="Execute adversarial scenarios and generate report",
    description=(
        "Runs the complete adversarial scenario suite against the application. "
        "LOCAL DEMO ONLY and explicitly disabled by default. Requires authenticated "
        "operator access, CSRF protection, and explicit enablement. Generates "
        "mock/stub-only reports in backend/reports/ (no real PayPal operations)."
    ),
    responses={
        200: {"description": "Adversarial execution completed. Summary returned."},
        403: {"description": "Forbidden - runner disabled or not authorized for local demo execution."},
        409: {"description": "Conflict - adversarial run already in progress."},
        504: {"description": "Timeout - adversarial run exceeded bounded execution time."},
    },
)
def run_adversarial_scenarios(request: Request) -> dict:
    """Execute all adversarial scenarios and write reports (guarded)."""
    if not _is_local_demo_context(request) or not _runner_explicitly_enabled(request):
        raise AdversarialRunnerDisabledError(
            "Adversarial runner is disabled. Explicit local-demo enablement is required."
        )

    settings = getattr(request.app.state, "settings", None)
    timeout_seconds = int(getattr(settings, "adversarial_runner_timeout_seconds", 300) or 300)

    if not _RUN_LOCK.acquire(blocking=False):
        raise AdversarialRunnerBusyError()

    try:
        def _execute() -> dict:
            # Lazy import to avoid circular dependency
            from app.security_testing.reporting import render_json, render_markdown
            from tests.adversarial.runner import run_all_scenarios

            # Fixed, mock/stub-only suite execution only; no arbitrary args/paths/commands.
            report = run_all_scenarios()

            json_path, markdown_path = _get_report_paths()
            json_path.parent.mkdir(parents=True, exist_ok=True)

            json_text = render_json(report)
            markdown_text = render_markdown(report)

            # Verify no secrets before writing
            _verify_no_secrets_in_report(json_text)
            _verify_no_secrets_in_report(markdown_text)

            json_path.write_text(json_text, encoding="utf-8", newline="\n")
            markdown_path.write_text(markdown_text, encoding="utf-8", newline="\n")

            return {
                "scenarios_total": report.total,
                "passed": report.passed,
                "failed": report.failed,
                "errors": report.errored,
                "skipped": report.skipped,
                "invariants_total": report.invariants_total,
                "invariants_verified": report.invariants_verified,
                "all_passed": report.all_passed,
                "json_report": str(json_path),
                "markdown_report": str(markdown_path),
            }

        with ThreadPoolExecutor(max_workers=1, thread_name_prefix="adversarial-run") as executor:
            future = executor.submit(_execute)
            try:
                return future.result(timeout=timeout_seconds)
            except FuturesTimeoutError as exc:
                logger.warning("adversarial_runner_timeout")
                # Best-effort: worker may continue in background thread until completion; lock
                # is held until this returns to prevent concurrent/repeated expensive runs.
                raise AdversarialRunnerTimeoutError() from exc
            except AppError:
                raise
            except Exception as exc:  # noqa: BLE001 - fail closed without leaking internals
                logger.error("adversarial_runner_failed", extra={"error_type": type(exc).__name__})
                raise AdversarialRunnerFailedError() from exc
    finally:
        _RUN_LOCK.release()